    def build_tool(
        self,
        gap_description: str,
        feedback_ids: list[str] = None,
        evolution_ids: list[str] = None,
        feedback_context: str = "",
        max_retries: int = 3,
        enable_research: bool = True
    ) -> ToolBuildResult:
        """Build a new tool to fill an identified gap."""
        
        feedback_ids = feedback_ids or []
        evolution_ids = evolution_ids or []
        
        # Get ALL existing tools for duplicate check (not just MCP)
        existing_tools = self.get_existing_tools()
        existing_tools_str = "\n".join(existing_tools) if existing_tools else "None"
        
        # Get system info
        import sys as _sys
        python_version = f"{_sys.version_info.major}.{_sys.version_info.minor}.{_sys.version_info.micro}"
        
        # Find available API keys in environment
        api_key_patterns = ['_API_KEY', '_TOKEN', '_SECRET', '_APIKEY']
        available_api_keys = [
            key for key in os.environ.keys() 
            if any(pattern in key.upper() for pattern in api_key_patterns)
            and os.environ.get(key)  # Has a value
        ]
        api_keys_str = ", ".join(sorted(available_api_keys)) if available_api_keys else "None detected"
        
        # Research via Jarvis (Ouroboros pattern) if enabled
        research_context = "No research needed for this tool."
        if enable_research and self._needs_research(gap_description):
            research_query = self._build_research_query(gap_description)
            print(f"🔍 Researching via Jarvis: {research_query[:80]}...")
            research_result = self.research_via_jarvis(research_query)
            if research_result:
                research_context = research_result
                print(f"✅ Research complete ({len(research_result)} chars)")
        
        # Build the prompt
        prompt = BUILD_PROMPT.format(
            gap_description=gap_description,
            feedback_context=feedback_context or "No specific feedback provided",
            existing_tools=existing_tools_str,
            python_version=python_version,
            available_api_keys=api_keys_str,
            available_packages=", ".join(sorted(AVAILABLE_PACKAGES)),
            research_context=research_context
        )
        
        retries = 0
        last_error = ""
        
        while retries < max_retries:
            try:
                # Ask LLM to generate the tool
                if retries > 0:
                    error_context = f"\n\nPREVIOUS ATTEMPT FAILED:\n{last_error}\n\nPlease fix and try again."
                    
                    # Detect network/connection errors and add proxy instructions
                    if self._is_network_error(last_error):
                        error_context += self._get_proxy_fix_instructions()
                    
                    prompt += error_context
                
                response = self.provider.chat(
                    prompt,
                    system_prompt="You are an expert Python developer creating tools for a voice assistant. Always respond with valid JSON only, no explanations.",
                    max_tokens=4096  # Need enough tokens for full tool code
                )
                
                # Parse response
                result = self._parse_llm_response(response)
                
                if result.get('action') == 'SKIP_MCP_EXISTS':
                    return ToolBuildResult(
                        success=False,
                        status="skipped_mcp",
                        message=f"MCP tool already exists: {result.get('skip_reason', 'unknown')}"
                    )
                
                if result.get('action') == 'SKIP_TRIVIAL':
                    return ToolBuildResult(
                        success=False,
                        status="skipped_trivial",
                        message=f"Tool deemed trivial: {result.get('skip_reason', 'unknown')}"
                    )
                
                if result.get('action') == 'SKIP_DUPLICATE':
                    return ToolBuildResult(
                        success=False,
                        status="skipped_duplicate",
                        message=f"Similar tool already exists: {result.get('skip_reason', 'unknown')}"
                    )
                
                # Validate and create tool
                return self._create_tool(
                    result,
                    gap_description,
                    feedback_ids,
                    evolution_ids,
                    existing_tools,
                    retries
                )
                
            except Exception as e:
                last_error = str(e)
                retries += 1
                if retries >= max_retries:
                    return ToolBuildResult(
                        success=False,
                        status="failed",
                        message=f"Failed after {max_retries} attempts: {last_error}",
                        retries_used=retries
                    )
        
        return ToolBuildResult(
            success=False,
            status="failed",
            message="Unknown error"
        )
    
    def _parse_llm_response(self, response: str) -> dict:
        """Parse LLM response, handling markdown code blocks and common issues."""
        original = response
        
        # Try to extract JSON from markdown code block
        if "```json" in response:
            # Try with closing ``` first
            match = re.search(r'```json\s*(.*?)\s*```', response, re.DOTALL)
            if match:
                response = match.group(1)
            else:
                # Handle missing closing ``` (truncated response)
                start_idx = response.find("```json") + 7
                response = response[start_idx:].strip()
        elif "```" in response:
            match = re.search(r'```\s*(.*?)\s*```', response, re.DOTALL)
            if match:
                response = match.group(1)
            else:
                # Handle missing closing ``` 
                start_idx = response.find("```") + 3
                response = response[start_idx:].strip()
        
        # Clean up common JSON issues from local models
        response = response.strip()
        
        # Try to parse as-is first
        try:
            return json.loads(response)
        except json.JSONDecodeError:
            pass
        
        # Try to extract and fix python_code field (common issue: unescaped newlines)
        extracted_code, fixed_response = self._extract_python_code_field(response)
        if extracted_code:
            try:
                return json.loads(fixed_response)
            except json.JSONDecodeError:
                pass
        
        # Try to repair common JSON issues
        repaired = self._repair_json(response)
        try:
            return json.loads(repaired)
        except json.JSONDecodeError as e:
            # Try to find any JSON object in the response
            json_match = re.search(r'\{.*\}', response, re.DOTALL)
            if json_match:
                try:
                    # Also try extracting python_code from the extracted JSON
                    _, fixed_json = self._extract_python_code_field(json_match.group(0))
                    return json.loads(self._repair_json(fixed_json))
                except:
                    pass
            raise ValueError(f"Failed to parse JSON: {e}\nResponse preview: {original[:500]}...")
    
    def _repair_json(self, text: str) -> str:
        """Attempt to repair common JSON issues from local models."""
        # Remove trailing commas before ] or }
        text = re.sub(r',\s*([}\]])', r'\1', text)
        
        # Try to close unclosed strings/brackets
        # Count brackets
        open_braces = text.count('{') - text.count('}')
        open_brackets = text.count('[') - text.count(']')
        
        # Add closing brackets if needed
        if open_braces > 0:
            text += '}' * open_braces
        if open_brackets > 0:
            text += ']' * open_brackets
        
        # Try to close unclosed strings (find last unclosed quote)
        in_string = False
        last_quote_pos = -1
        i = 0
        while i < len(text):
            c = text[i]
            if c == '\\' and i + 1 < len(text):
                i += 2  # Skip escaped char
                continue
            if c == '"':
                in_string = not in_string
                if in_string:
                    last_quote_pos = i
            i += 1
        
        if in_string and last_quote_pos >= 0:
            # String wasn't closed - add closing quote
            text += '"'
        
        return text
    
    def _extract_python_code_field(self, text: str) -> tuple[str | None, str]:
        """
        Extract python_code field separately to handle unescaped newlines.
        Returns (extracted_code, text_with_placeholder) or (None, original_text).
        """
        # Look for "python_code": followed by a string
        # The code often has unescaped newlines which break JSON
        
        # Pattern: "python_code": "...code..." (with possible newlines)
        # We look for the field and try to find where it ends
        
        match = re.search(r'"python_code"\s*:\s*"', text)
        if not match:
            return None, text
        
        start_idx = match.end()  # Position right after opening quote
        
        # Find the end of the python_code string
        # This is tricky because we need to handle:
        # - Escaped quotes \"
        # - The actual closing quote followed by , or }
        
        # Walk through finding the real end
        i = start_idx
        depth = 0
        while i < len(text):
            c = text[i]
            
            # Handle escapes
            if c == '\\' and i + 1 < len(text):
                i += 2
                continue
            
            # Track nested braces for f-strings like {{
            if c == '{':
                depth += 1
            elif c == '}':
                depth -= 1
            
            # Found potential end quote
            if c == '"':
                # Check if followed by , or } or whitespace then , or }
                rest = text[i+1:i+20].strip()
                if rest.startswith(',') or rest.startswith('}'):
                    # This is the end
                    code = text[start_idx:i]
                    
                    # Properly escape the code for JSON
                    escaped_code = (code
                        .replace('\\', '\\\\')  # Escape backslashes first
                        .replace('\n', '\\n')   # Escape newlines
                        .replace('\r', '\\r')   # Escape carriage returns  
                        .replace('\t', '\\t')   # Escape tabs
                        .replace('"', '\\"'))   # Escape quotes
                    
                    # Replace in original text
                    new_text = text[:start_idx] + escaped_code + text[i:]
                    return code, new_text
            
            i += 1
        
        return None, text
    
    def _create_tool(
        self,
        spec: dict,
        gap_description: str,
        feedback_ids: list[str],
        evolution_ids: list[str],
        existing_tools: list[str],
        retries: int
    ) -> ToolBuildResult:
        """Create the tool files and verify."""
        
        tool_name = spec.get('tool_name', '').strip()
        if not tool_name or not re.match(r'^[a-z][a-z0-9_]*$', tool_name):
            raise ValueError(f"Invalid tool name: {tool_name}")
        
        # Check for new packages needed
        packages_needed = spec.get('packages_needed', [])
        new_packages = [p for p in packages_needed if p.lower() not in AVAILABLE_PACKAGES]
        
        # Check if new API key required
        requires_new_api_key = spec.get('requires_new_api_key', False)
        suggested_env_var = spec.get('suggested_env_var')
        
        # Determine target directory
        needs_manual_setup = new_packages or requires_new_api_key
        if needs_manual_setup:
            target_dir = PENDING_DIR
            status = "pending_review"
            if requires_new_api_key:
                status = "pending_api_key"
        else:
            target_dir = AUTO_TOOLS_DIR
            status = "created"
        
        # Create files
        py_path = target_dir / f"{tool_name}.py"
        json_path = target_dir / f"{tool_name}.tool.json"
        report_path = target_dir / f"{tool_name}.report.json"
        
        created_at = datetime.now().isoformat()
        
        # Write Python file
        python_code = spec.get('python_code', '')
        with open(py_path, 'w') as f:
            f.write(python_code)
        
        # Make executable
        os.chmod(py_path, 0o755)
        
        # Write JSON config
        json_config = {
            "enabled": True,
            "name": tool_name,
            "description": spec.get('description', ''),
            "script": f"{tool_name}.py",
            "parameters": spec.get('parameters', {"type": "object", "properties": {}}),
            "permissions": spec.get('permissions', {
                "dangerous": False,
                "bash": False,
                "network": False,
                "filesystem": False,
                "auto_approve": True
            }),
            "test_input": spec.get('test_input', {}),
            "expected_output_contains": spec.get('expected_output_contains', []),
            "auto_generated": True,
            "created_at": created_at,
            "feedback_ids": feedback_ids
        }
        
        with open(json_path, 'w') as f:
            json.dump(json_config, f, indent=2)
        
        # Verify the tool (if no new packages needed)
        verification_passed = False
        verification_output = ""
        test_output = ""
        
        if not new_packages:
            verification_passed, verification_output, test_output = self._verify_tool(
                py_path,
                spec.get('test_input', {})
            )
            
            if not verification_passed:
                # Clean up failed tool
                py_path.unlink(missing_ok=True)
                json_path.unlink(missing_ok=True)
                raise ValueError(f"Verification failed: {verification_output}")
        
        # Create report card
        report_card = ToolReportCard(
            tool_name=tool_name,
            created_at=created_at,
            created_by="auto_builder",
            mode=self.mode,
            gap_description=gap_description,
            purpose=spec.get('purpose', ''),
            feedback_ids=feedback_ids,
            evolution_ids=evolution_ids,
            capabilities=spec.get('capabilities', []),
            parameters={k: v.get('description', '') for k, v in spec.get('parameters', {}).get('properties', {}).items()},
            verification_passed=verification_passed,
            verification_output=verification_output,
            test_input_used=spec.get('test_input', {}),
            test_output=test_output,
            packages_required=packages_needed,
            packages_new=new_packages,
            mcp_alternatives_checked=existing_tools,
            mcp_overlap_reason="No existing tool found for this specific use case",
            builder_provider=self.provider_type,
            builder_model=self.model,
            generation_retries=retries,
            requires_api_key=requires_new_api_key,
            suggested_env_var=suggested_env_var
        )
        
        # Save report card
        with open(report_path, 'w') as f:
            json.dump(asdict(report_card), f, indent=2)
        
        # Log the creation
        self._log_creation(report_card, status)
        
        # Build status message
        pending_reasons = []
        if new_packages:
            pending_reasons.append(f"packages: {new_packages}")
        if requires_new_api_key:
            pending_reasons.append(f"API key needed: {suggested_env_var or 'unspecified'}")
        
        message = f"Tool created: {tool_name}"
        if pending_reasons:
            message += f" (pending review - {', '.join(pending_reasons)})"
        
        return ToolBuildResult(
            success=True,
            tool_name=tool_name,
            tool_path=str(py_path),
            status=status,
            message=message,
            report_card=asdict(report_card),
            retries_used=retries,
            needs_packages=new_packages
        )
    
    def _verify_tool(self, py_path: Path, test_input: dict) -> tuple[bool, str, str]:
        """Verify the tool works."""
        
        # 1. Syntax check
        try:
            with open(py_path) as f:
                code = f.read()
            ast.parse(code)
        except SyntaxError as e:
            return False, f"Syntax error: {e}", ""
        
        # 2. Import check (try to import without running)
        try:
            result = subprocess.run(
                [sys.executable, "-c", f"import ast; ast.parse(open('{py_path}').read())"],
                capture_output=True,
                text=True,
                timeout=10
            )
            if result.returncode != 0:
                return False, f"Import check failed: {result.stderr}", ""
        except subprocess.TimeoutExpired:
            return False, "Import check timed out", ""
        
        # 3. Run with test input
        try:
            test_input_json = json.dumps(test_input)
            # Run from project root so lib/ is accessible
            project_root = Path(__file__).parent.parent
            result = subprocess.run(
                [sys.executable, str(py_path), test_input_json],
                capture_output=True,
                text=True,
                timeout=30,
                cwd=str(project_root)
            )
            
            if result.returncode != 0:
                return False, f"Runtime error: {result.stderr}", result.stdout
            
            # Check output is valid JSON
            try:
                output = json.loads(result.stdout)
                if not isinstance(output, dict):
                    return False, "Output is not a JSON object", result.stdout
                if 'ok' not in output:
                    return False, "Output missing 'ok' field", result.stdout
                if 'speech' not in output:
                    return False, "Output missing 'speech' field", result.stdout
            except json.JSONDecodeError:
                return False, f"Output is not valid JSON: {result.stdout[:200]}", result.stdout
            
            return True, "All checks passed", result.stdout
            
        except subprocess.TimeoutExpired:
            return False, "Execution timed out (30s)", ""
        except Exception as e:
            return False, f"Verification error: {e}", ""
    
    def _is_network_error(self, error_message: str) -> bool:
        """Detect if an error is network/connection related."""
        network_indicators = [
            'failed to connect',
            'connection refused',
            'connectionerror',
            'connection error',
            'read timed out',
            'could not resolve host',
            'no route to host',
            'network is unreachable',
            'timeout',
            'ssl: certificate_verify_failed',
            'getaddrinfo failed',
            'name or service not known',
            'errno 111',
            'errno 110',
            'curl',
            'yahoo.com',  # Specific to yfinance
            'fc.yahoo.com',
        ]
        error_lower = error_message.lower()
        return any(indicator in error_lower for indicator in network_indicators)
    
