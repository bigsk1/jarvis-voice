    parser.add_argument("--mode", default="cloud", choices=["cloud", "local"])
    parser.add_argument("--gap", help="Gap description to fill")
    parser.add_argument("--list-pending", action="store_true", help="List pending tools")
    parser.add_argument("--approve", help="Approve a pending tool")
    
    args = parser.parse_args()
    
    if args.list_pending:
        pending = list_pending_tools()
        print(json.dumps(pending, indent=2))
    elif args.approve:
        if approve_pending_tool(args.approve, install_packages=True):
            print(f"✅ Approved: {args.approve}")
        else:
            print(f"❌ Not found: {args.approve}")
    elif args.gap:
        builder = ToolBuilder(mode=args.mode)
        result = builder.build_tool(args.gap)
        print(json.dumps(asdict(result) if hasattr(result, '__dict__') else result.__dict__, indent=2, default=str))
    else:
        parser.print_help()

